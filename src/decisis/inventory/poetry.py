from __future__ import annotations

import re
import tomllib

from .shape import Inventory, make_purl, package_id, pypi_name, text_digest

FORMAT = "poetry"
SIBLINGS = ("pyproject.toml",)
NOT_PYPI = ("directory", "file", "url", "git")
NAME = re.compile(r"\s*([A-Za-z0-9](?:[A-Za-z0-9._-]*[A-Za-z0-9])?)")


def detect(text: str, filename: str) -> bool:
    if filename == "poetry.lock" or "@generated by Poetry" in text[:300]:
        return True
    try:
        doc = tomllib.loads(text)
    except tomllib.TOMLDecodeError:
        return False
    meta = doc.get("metadata")
    return isinstance(meta, dict) and "content-hash" in meta and isinstance(doc.get("package"), list)


def lock_version(doc: dict) -> str:
    version = str((doc.get("metadata") or {}).get("lock-version") or "1.0")
    if version.split(".")[0] not in ("1", "2"):
        raise ValueError(f"poetry.lock lock-version {version} is not one audit reads; it reads lock-version 1.x and 2.x")
    return version


def dev_mark(p: dict) -> bool | None:
    if isinstance(p.get("category"), str):
        return p["category"] != "main"
    groups = p.get("groups")
    if isinstance(groups, list) and groups:
        return "main" not in groups
    return None


def not_pypi(p: dict) -> str:
    source = p.get("source") or {}
    if source.get("type") in NOT_PYPI:
        return f"poetry.lock installs it from a {source['type']} source ({source.get('url', '')}), not from PyPI"
    return ""


def requirement_name(spec: str) -> str:
    m = NAME.match(spec)
    return m[1] if m else ""


def poetry_roots(poetry: dict) -> list[tuple[str, bool, str]]:
    out = [(n, False, "") for n in poetry.get("dependencies") or {} if n.lower() != "python"]
    out += [(n, True, " (dev-dependencies)") for n in poetry.get("dev-dependencies") or {}]
    for group, body in sorted((poetry.get("group") or {}).items()):
        out += [(n, group != "main", f" (group {group})") for n in (body or {}).get("dependencies") or {}]
    return out


def project_roots(pyproject: dict) -> list[tuple[str, bool, str]]:
    project = pyproject.get("project") or {}
    out = [(requirement_name(s), False, "") for s in project.get("dependencies") or []]
    for extra, reqs in sorted((project.get("optional-dependencies") or {}).items()):
        out += [(requirement_name(s), False, f" (extra {extra})") for s in reqs]
    for group, reqs in sorted((pyproject.get("dependency-groups") or {}).items()):
        out += [(requirement_name(s), True, f" (group {group})") for s in reqs if isinstance(s, str)]
    return out


def roots(pyproject: dict) -> list[tuple[str, bool, str]]:
    poetry = (pyproject.get("tool") or {}).get("poetry") or {}
    return [r for r in poetry_roots(poetry) + project_roots(pyproject) if r[0]]


def describe(spec) -> str:
    if isinstance(spec, str):
        return spec
    if not isinstance(spec, dict):
        return ""
    text = str(spec.get("version") or "")
    if spec.get("markers"):
        text += f"; {spec['markers']}"
    return text + (" (optional)" if spec.get("optional") else "")


def requirements(p: dict) -> list[tuple[str, str]]:
    out = []
    for name, spec in (p.get("dependencies") or {}).items():
        for one in spec if isinstance(spec, list) else [spec]:
            out.append((name, describe(one)))
    return out


def package(p: dict, filename: str, repo: str) -> tuple[dict, str]:
    name, version = pypi_name(p["name"]), str(p.get("version") or "")
    reason = not_pypi(p) or ("" if version else "the lockfile gives no version")
    pkg = {"id": package_id("PyPI", name, version), "ecosystem": "PyPI", "name": name, "version": version,
           "purl": make_purl("pypi", name, version), "unresolved": reason}
    return pkg, f"{repo}:{filename}#{name}@{version}"


def link_roots(inv: Inventory, by_name: dict, pyproject: dict) -> None:
    for name, dev, note in roots(pyproject):
        for key in by_name.get(pypi_name(name)) or []:
            inv.depends(None, key, f"pyproject.toml requires {name}{note}", dev)


def read(text: str, filename: str, repo: str, siblings: dict[str, str] | None = None) -> tuple[list[dict], list[dict]]:
    doc = tomllib.loads(text)
    version = lock_version(doc)
    pyproject_text = (siblings or {}).get("pyproject.toml")
    packages = [p for p in doc.get("package") or [] if isinstance(p, dict) and p.get("name")]
    inv = Inventory(repo, "poetry-lockfile", text_digest(text, *([pyproject_text] if pyproject_text is not None else [])))
    by_name: dict[str, list[tuple]] = {}
    for p in packages:
        key = (pypi_name(p["name"]), str(p.get("version") or ""))
        by_name.setdefault(key[0], []).append(key)
        inv.add(key, *package(p, filename, repo), dev=dev_mark(p))
    for p in packages:
        key = (pypi_name(p["name"]), str(p.get("version") or ""))
        for name, spec in requirements(p):
            for target in by_name.get(pypi_name(name)) or []:
                inv.depends(key, target, f"{p['name']} {key[1]} requires {name} {spec}".rstrip())
    if pyproject_text is not None:
        link_roots(inv, by_name, tomllib.loads(pyproject_text))
    elif not any(dev_mark(p) is not None for p in packages):
        inv.note(f"{filename} (lock-version {version}) does not say which packages are development dependencies and there is "
                 "no pyproject.toml next to it, so the dev split is unknown and every package counts as shipped")
    inv.adopt_orphans(f"listed in {filename} with no dependency on it")
    return inv.result()
