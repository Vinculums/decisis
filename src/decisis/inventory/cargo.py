from __future__ import annotations

import tomllib

from .shape import Inventory, make_purl, package_id, text_digest

FORMAT = "cargo"
SIBLINGS: tuple[str, ...] = ()


def detect(text: str, filename: str) -> bool:
    return filename == "Cargo.lock" or "@generated by Cargo" in text[:300]


def _pick(by_name: dict, ref: str) -> tuple | None:
    parts = ref.split(" ", 2)
    found = by_name.get(parts[0]) or []
    if len(parts) > 1:
        found = [p for p in found if p.get("version") == parts[1]]
    return (found[0]["name"], found[0].get("version")) if found else None


def read(text: str, filename: str, repo: str, siblings: dict[str, str] | None = None) -> tuple[list[dict], list[dict]]:
    doc = tomllib.loads(text)
    packages = [p for p in doc.get("package") or [] if isinstance(p, dict) and p.get("name")]
    inv = Inventory(repo, "cargo-lockfile", text_digest(text))
    by_name: dict[str, list[dict]] = {}
    for p in packages:
        key = (p["name"], p.get("version"))
        by_name.setdefault(p["name"], []).append(p)
        if "source" not in p:
            inv.root(key)
            continue
        version = p.get("version") or ""
        pkg = {"id": package_id("crates.io", p["name"], version), "ecosystem": "crates.io", "name": p["name"], "version": version,
               "purl": make_purl("cargo", p["name"], version), "unresolved": "" if version else "the lockfile gives no version"}
        inv.add(key, pkg, f"{repo}:{filename}#{p['name']}@{version}")
    for p in packages:
        key = (p["name"], p.get("version"))
        for ref in p.get("dependencies") or []:
            target = _pick(by_name, ref)
            if target is not None:
                inv.depends(None if "source" not in p else key, target, f"{p['name']} {p.get('version')} depends on {ref}")
    return inv.result()
